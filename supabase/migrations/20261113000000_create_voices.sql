-- お客様の声（voices）テーブル — Maruai プロジェクト用
-- Supabase の SQL Editor に貼り付けて実行しても、そのまま動きます。
--
-- 方針:
--  * published の既定は false。掲載許可を確認した声だけ true にする。
--  * 匿名（サイト訪問者）は published=true の行だけ読める。書き込みは不可。
--  * 架空の声は入れない（事業者が作成した口コミを顧客の声として表示すると、
--    景品表示法のステルスマーケティング規制に抵触するおそれがある）。

create table if not exists public.voices (
  id         bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  published  boolean     not null default false,
  sort       integer     not null default 0,
  rating     smallint    not null default 5 check (rating between 1 and 5),
  headline   text,
  body       text        not null,
  who        text,        -- 例: 阿見町・60代・男性
  service    text,        -- 例: 外壁塗装
  work_id    bigint references public.works(id) on delete set null,
  city_slug  text
);

comment on table public.voices is 'Maruai お客様の声。published=true（掲載許可済み）のみ公開。';
comment on column public.voices.published is '掲載許可を確認してから true にする';
comment on column public.voices.work_id is '関連する施工事例（works.id）。カードから事例ページへリンクする';

alter table public.voices enable row level security;

drop policy if exists "public can read published voices" on public.voices;
create policy "public can read published voices"
  on public.voices for select
  to anon, authenticated
  using (published = true);
