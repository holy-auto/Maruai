create table if not exists cities (
  slug text primary key, name text not null,
  intro text not null, climate_note text,
  nearby text[] default '{}', sort int default 0
);

-- 施工事例（新デザインの Example 形状に対応）。
-- 旧 region ページ互換のため city_slug / service / paint / built_years / body も残す。
create table if not exists works (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  published   boolean     not null default true,
  sort        integer     not null default 0,
  category    text        not null,
  title       text        not null,
  location    text        not null default '',
  area        text        not null default '',
  period      text        not null default '',
  description text        not null default '',
  before_url  text        not null default '',
  after_url   text        not null default '',
  features    text[]      not null default '{}',
  testimonial text        not null default '',
  -- 旧スキーマ互換（任意） --
  city_slug   text references cities(slug),
  service     text,
  paint       text,
  built_years int,
  body        text
);

-- お客様の声。published は既定 false（掲載許可を確認してから true にする）。
create table if not exists voices (
  id         bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  published  boolean     not null default false,
  sort       integer     not null default 0,
  rating     smallint    not null default 5 check (rating between 1 and 5),
  headline   text,
  body       text        not null,
  who        text,
  service    text,
  work_id    bigint references works(id) on delete set null,
  city_slug  text references cities(slug)
);

create table if not exists posts (
  slug text primary key, title text not null,
  excerpt text, body text,
  published boolean default true, published_at timestamptz default now()
);

-- お問い合わせ（フォーム送信先）。source: home=トップ, contact=問い合わせページ, careers=採用。
-- 電話番号や概算シミュレーション結果などの付随情報は payload(jsonb) に格納する。
create table if not exists contact_submissions (
  id         uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  source     text not null check (source = any (array['contact'::text, 'home'::text, 'careers'::text])),
  name       text not null,
  email      text,
  message    text,
  payload    jsonb not null default '{}'::jsonb
);

-- ---------- RLS：公開ページは read のみ、問い合わせは insert のみ ----------
alter table cities              enable row level security;
alter table works               enable row level security;
alter table voices              enable row level security;
alter table posts               enable row level security;
alter table contact_submissions enable row level security;

create policy "read cities"  on cities  for select using (true);
create policy "read works"   on works   for select using (published);
create policy "read voices"  on voices  for select using (published);
create policy "read posts"   on posts   for select using (published);
create policy "anyone can submit contact" on contact_submissions for insert
  with check (source = any (array['contact'::text, 'home'::text, 'careers'::text]));
-- contact_submissions は select ポリシーを作らない＝匿名では読めない（管理はダッシュボード/service_role）

